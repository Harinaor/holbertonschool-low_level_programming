#include "3-calc.h"

/**
 * op_add - additionne deux entiers
 * @num1: un entier
 * @num2: un autre entier
 * Return: num1 + num2
 */
int op_add(int num1, int num2)
{
	return (num1 + num2);
}

/**
 * op_sub - soustrait deux entiers
 * @num1: un entier
 * @num2: un autre entier
 * Return: num1 - num2
 */
int op_sub(int num1, int num2)
{
	return (num1 - num2);
}

/**
 * op_mul - multiplie deux entiers
 * @num1: un entier
 * @num2: un autre entier
 * Return: num1 * num2
 */
int op_mul(int num1, int num2)
{
	return (num1 * num2);
}

/**
 * op_div - divise deux entiers
 * @num1: un entier
 * @num2: un autre entier
 * Return: num1 / num2
 */
int op_div(int num1, int num2)
{
	return (num1 / num2);
}

/**
 * op_mod - retourne le modulo de la division de deux entiers
 * @num1: un entier
 * @num2: un autre entier
 * Return: num1 % num2
 */
int op_mod(int num1, int num2)
{
	return (num1 % num2);
}
